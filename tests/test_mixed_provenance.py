"""Run provenance in every consumer of evaluator outputs.

End to end, offline: complete A/v1 checkpoints are assembled by the evaluator
under B/v1.1 with --allow-checkpoint-mismatch (zero new evaluations). Every
consumer must reject the result by default, and with --allow-mixed must report
the mixture and take model / prompt version from the row stamps. Clean stamped
inputs and unstamped legacy inputs keep working and give the same numbers; with
CTE_REFERENCE_RESULTS the released reports are regenerated byte for byte.
"""
