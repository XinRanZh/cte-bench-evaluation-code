@unittest.skipUnless(REF, "set CTE_REFERENCE_RESULTS to the HF reference_results/ directory")
class TestReleasedLegacyReportsUnchanged(unittest.TestCase):
    """The released reports regenerate byte for byte from the unstamped legacy outputs."""

    def setUp(self):
        self.root = Path(REF).resolve().parent
        self.tmp_obj = tempfile.TemporaryDirectory()
        self.tmp = Path(self.tmp_obj.name)

    def tearDown(self):
        self.tmp_obj.cleanup()

    def _regen(self, script, *args, cwd=None):
        out = self.tmp / f"{script}.json"
        subprocess.run([sys.executable, str(ROOT / "scripts" / script), *args, "--json", str(out)],
                       cwd=cwd or ROOT, check=True, capture_output=True)
        return out.read_bytes()

    def test_paired_report(self):
        got = self._regen(
            "score_paired.py",
            "--pair", "DeepSeek V4-Flash", "reference_results/raw/deepseek_v4_flash_tf1step_sliding_k20.json",
            "reference_results/no_effect_v1_raw/deepseek_v4_flash_no_effect_v1_tf1step_sliding_k20.json",
            "--pair", "Kimi K2.5", "reference_results/raw/kimi_k25_tf1step_sliding_k20.json",
            "reference_results/no_effect_v1_raw/kimi_k25_no_effect_v1_tf1step_sliding_k20.json",
            "--core-jsonl", "counterfactuals/core_v1.jsonl", "--no-effect-jsonl", "counterfactuals/no_effect_v1.jsonl",
            cwd=self.root)
        self.assertEqual(got, (self.root / "reference_results" / "no_effect_v1_paired.json").read_bytes())

    def test_audit_reasoning_and_renamed_reports(self):
        for script, released in (("audit_reference_results.py", "reference_audit.json"),
                                 ("score_reasoning_pairs.py", "reasoning_pairs.json"),
                                 ("score_renamed_variant.py", "renamed_variant_scores.json")):
            with self.subTest(script=script):
                got = self._regen(script, "--dataset-root", str(self.root))
                self.assertEqual(got, (self.root / "reference_results" / released).read_bytes())

    def test_leaderboard_on_a_legacy_output(self):
        path = self.root / "reference_results" / "raw" / "deepseek_v4_flash_tf1step_sliding_k20.json"
        rows = lb.aggregate([path])
        self.assertEqual({r["provenance"] for r in rows}, {prov.LEGACY})
        data = json.loads(path.read_text())
        items = [r for r in data["per_item"] if r and "error" not in r]
        self.assertEqual(sum(r["value_match"] for r in rows), sum(r["n_value_match"] for r in items))
        # the 145 calls that returned a provider error are not scored
        self.assertEqual(sum(r["suffix_total"] for r in rows), sum(r["suffix_len"] for r in items) - 145)
        self.assertEqual(sum(r["infra_excluded_calls"] for r in rows), 154)
        self.assertEqual({r["model_id"] for r in rows}, {data["model"]})
        self.assertTrue(all(path.name in r["model"] and "core_v1.jsonl" in r["model"] for r in rows))


