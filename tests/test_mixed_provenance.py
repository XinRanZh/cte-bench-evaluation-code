BUDGET = 40
CORE_PATH = ROOT / "counterfactuals" / "core_v1.jsonl"
NE_PATH = ROOT / "counterfactuals" / "no_effect_v1.jsonl"
CORE = sp.load_jsonl(CORE_PATH)
NE = sp.load_jsonl(NE_PATH)


def _offline_litellm():
    def completion(*_a, **_k):
        raise AssertionError("offline test: the evaluator must not call a model here")
    return types.SimpleNamespace(completion=completion, completion_cost=lambda **_k: 0.0)


def _config(cf_path, model, prompt_version):
    ns = types.SimpleNamespace(cf_jsonl=str(cf_path), model=model, strategy="sliding", window=20,
                               prompt_version=prompt_version, suffix_budget=BUDGET, thinking="off",
                               reasoning_effort="high", max_tokens=4000, no_explain=True, no_state=True)
    return E.checkpoint_run_config(ns)


def _oracle_rows(catalog, stamp=None):
    rows = []
    for r in catalog:
        steps = [{"suffix_idx": j, "op": s["op"], "args": s["args"], "predicted": s["response"],
                  "ground_truth": s["response"], "value_match": True, "status_match": True, "well_formed": True}
                 for j, s in enumerate(r["trace_counterfactual"][:BUDGET])]
        row = {"item_id": r["item_id"], "domain": r["domain"], "intervention_kind": r["intervention"]["kind"],
               "prefix_len": r["prefix_len"], "suffix_len": BUDGET, "n_well_formed": BUDGET,
               "n_value_match": BUDGET, "n_status_match": BUDGET, "first_value_mismatch_at": None,
               "expected_delay": None, "billing": {"n_calls": BUDGET}, "phase_a": steps,
               "phase_b": None, "phase_c": None}
        if stamp is not None:
            row[E.ROW_CONFIG_KEY] = stamp
            row[E.ROW_ID_KEY] = prov.catalog_row_id(r)
        rows.append(row)
    return rows


def _run_eval(cf_path, out, model, prompt_version, *extra):
    argv = ["eval_llm_counterfactual.py", "--cf-jsonl", str(cf_path), "--model", model, "--strategy", "sliding",
            "--window", "20", "--max-items", "1000", "--suffix-budget", str(BUDGET), "--no-explain", "--no-state",
            "--prompt-version", prompt_version, "--out", str(out), *extra]
    buf = io.StringIO()
    with mock.patch.object(sys, "argv", argv), mock.patch.dict(sys.modules, {"litellm": _offline_litellm()}), \
            contextlib.redirect_stdout(buf):
        E.main()
    return buf.getvalue()


def _assemble(tmp: Path, cf_path, catalog, name, ckpt_model, ckpt_pv, run_model, run_pv, *extra):
    """Write a complete checkpoint under (ckpt_model, ckpt_pv); finish the run under (run_model, run_pv)."""
    out = tmp / f"{name}.json"
    stamp = _config(cf_path, ckpt_model, ckpt_pv)
    lines = [json.dumps({E.CHECKPOINT_CONFIG_KEY: stamp})] + [json.dumps(r) for r in _oracle_rows(catalog, stamp)]
    Path(str(out) + ".ckpt.jsonl").write_text("\n".join(lines) + "\n")
    log = _run_eval(cf_path, out, run_model, run_pv, *extra)
    assert "0 items pending" in log, log
    return out


def _score_paired(*argv):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        sp.main(list(argv))
    return buf.getvalue()


def _leaderboard(*argv):
    buf = io.StringIO()
    with mock.patch.object(sys, "argv", ["leaderboard.py", *argv]), contextlib.redirect_stdout(buf):
        lb.main()
    return buf.getvalue()


class TestMixedAssemblyRejected(unittest.TestCase):
    """Codex's case: complete A/v1 checkpoints finished under B/v1.1 with the override."""

    @classmethod
    def setUpClass(cls):
        cls.tmp_obj = tempfile.TemporaryDirectory()
        cls.tmp = Path(cls.tmp_obj.name)
        cls.core = _assemble(cls.tmp, CORE_PATH, CORE, "core_mixed", "A", "v1", "B", "v1.1", "--allow-checkpoint-mismatch")
        cls.ne = _assemble(cls.tmp, NE_PATH, NE, "ne_mixed", "A", "v1", "B", "v1.1", "--allow-checkpoint-mismatch")

    @classmethod
    def tearDownClass(cls):
        cls.tmp_obj.cleanup()

    def test_evaluator_marked_the_outputs_mixed(self):
        for p in (self.core, self.ne):
            d = json.loads(p.read_text())
            self.assertTrue(d["mixed_run_configurations"])
            self.assertEqual({r[E.ROW_CONFIG_KEY]["model"] for r in d["per_item"]}, {"A"})
            self.assertEqual(d["model"], "B")

    def test_score_paired_rejects_by_default(self):
        with self.assertRaises(SystemExit) as cm:
            _score_paired("--core-run", str(self.core), "--no-effect-run", str(self.ne), "--label", "B")
        self.assertIn("mixed run provenance", str(cm.exception))
        self.assertIn("mixed_run_configurations=true", str(cm.exception))

    def test_score_paired_reports_the_mixture_with_allow_mixed(self):
        out = self.tmp / "paired_mixed.json"
        log = _score_paired("--core-run", str(self.core), "--no-effect-run", str(self.ne), "--label", "B",
                            "--allow-mixed", "--json", str(out))
        d = json.loads(out.read_text())
        m = d["models"]["B"]
        self.assertTrue(m["mixed_run_provenance"])
        self.assertTrue(m["provenance"]["mixed"])
        self.assertEqual(m["core_run"]["model"], "A")          # from the row stamps, not the declared "B"
        self.assertEqual(m["core_run"]["prompt_version"], "v1")
        self.assertEqual(m["core_run"]["provenance"], prov.MIXED)
        self.assertIn("WARNING: MIXED RUN PROVENANCE", m["warning"])
        self.assertEqual(d["mixed_run_provenance"], ["B"])
        self.assertIn("WARNING: MIXED RUN PROVENANCE", log)

    def test_leaderboard_rejects_by_default(self):
        with self.assertRaises(prov.MixedRunError):
            lb.aggregate([self.core])
        with self.assertRaises(SystemExit):
            _leaderboard("--result-jsons", str(self.core), "--out-dir", str(self.tmp / "lb_reject"))

    def test_leaderboard_reports_the_mixture_with_allow_mixed(self):
        out_dir = self.tmp / "lb_mixed"
        log = _leaderboard("--result-jsons", str(self.core), "--out-dir", str(out_dir), "--allow-mixed")
        self.assertIn("WARNING: MIXED RUN PROVENANCE", log)
        self.assertTrue(json.loads((out_dir / "provenance.json").read_text())["mixed_run_provenance"])
        self.assertTrue((out_dir / "leaderboard.md").read_text().startswith("> WARNING: MIXED RUN PROVENANCE"))
        self.assertIn("WARNING: MIXED RUN PROVENANCE", (out_dir / "per_model_summary.md").read_text())
        rows = lb.aggregate([self.core], allow_mixed=True)
        self.assertEqual({r["model_id"] for r in rows}, {"A"})
        self.assertEqual({r["prompt_version"] for r in rows}, {"v1"})
        self.assertEqual({r["provenance"] for r in rows}, {"MIXED"})
        self.assertEqual(sum(r["n_items"] for r in rows), 255)

    def test_other_consumers_reject_by_default(self):
        with self.assertRaises(prov.MixedRunError):
            ar.audit_file(self.core, CORE, "schedule")
        res = ar.audit_file(self.core, CORE, "schedule", allow_mixed=True)
        self.assertEqual(res["model"], "A")
        self.assertIn("WARNING: MIXED RUN PROVENANCE", res["warning"])
        with self.assertRaises(prov.MixedRunError):
            av2.aggregate_filtered(self.core, {})
        with self.assertRaises(prov.MixedRunError):
            core_v1.filter_core_results(json.loads(self.core.read_text())["per_item"]
                                        + [{"item_id": "x", "domain": "auth", "intervention_kind": "k"}])


class TestCleanAndLegacyInputs(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp_obj = tempfile.TemporaryDirectory()
        cls.tmp = Path(cls.tmp_obj.name)
        cls.core = _assemble(cls.tmp, CORE_PATH, CORE, "core_clean", "A", "v1", "A", "v1")
        cls.ne = _assemble(cls.tmp, NE_PATH, NE, "ne_clean", "A", "v1", "A", "v1")
        cls.core_legacy, cls.ne_legacy = cls.tmp / "core_legacy.json", cls.tmp / "ne_legacy.json"
        for path, cat in ((cls.core_legacy, CORE), (cls.ne_legacy, NE)):
            path.write_text(json.dumps({"model": "A", "strategy": "sliding", "window": 20, "thinking": "off",
                                        "suffix_budget": BUDGET, "n_items": len(cat), "per_item": _oracle_rows(cat)}))

    @classmethod
    def tearDownClass(cls):
        cls.tmp_obj.cleanup()

    def test_clean_stamped_pair_scores_like_the_legacy_pair(self):
        a, b = self.tmp / "clean.json", self.tmp / "legacy.json"
        _score_paired("--core-run", str(self.core), "--no-effect-run", str(self.ne), "--label", "A", "--json", str(a))
        _score_paired("--core-run", str(self.core_legacy), "--no-effect-run", str(self.ne_legacy), "--label", "A",
                      "--json", str(b))
        ca, cb = json.loads(a.read_text())["models"]["A"], json.loads(b.read_text())["models"]["A"]
        for k in ("effect_step_vm", "no_effect_vm", "no_effect_over_prediction_rate", "complete", "pairs_scored"):
            self.assertEqual(ca[k], cb[k])
        self.assertEqual(ca["effect_step_vm"]["value"], 100.0)
        self.assertFalse(ca["provenance"]["mixed"])
        self.assertEqual((ca["core_run"]["model"], ca["core_run"]["prompt_version"]), ("A", "v1"))
        self.assertNotIn("provenance", cb)            # legacy reports keep their earlier form
        self.assertNotIn("mixed_run_provenance", ca)

    def test_legacy_and_stamped_inputs_need_allow_mixed(self):
        with self.assertRaises(SystemExit) as cm:
            _score_paired("--core-run", str(self.core_legacy), "--no-effect-run", str(self.ne), "--label", "A")
        self.assertIn("cannot be verified to agree", str(cm.exception))
        out = self.tmp / "legacy_plus_stamped.json"
        _score_paired("--core-run", str(self.core_legacy), "--no-effect-run", str(self.ne), "--label", "A",
                      "--allow-mixed", "--json", str(out))
        self.assertTrue(json.loads(out.read_text())["models"]["A"]["mixed_run_provenance"])

    def test_stamped_runs_with_different_prompt_versions_are_not_paired(self):
        ne_v11 = _assemble(self.tmp, NE_PATH, NE, "ne_v11", "A", "v1.1", "A", "v1.1")
        with self.assertRaises(SystemExit) as cm:
            _score_paired("--core-run", str(self.core), "--no-effect-run", str(ne_v11), "--label", "A")
        self.assertIn("prompt_version", str(cm.exception))

    def test_leaderboard_labels_clean_inputs_and_keeps_legacy_apart(self):
        out_dir = self.tmp / "lb_clean"
        log = _leaderboard("--result-jsons", str(self.core), "--out-dir", str(out_dir))
        self.assertNotIn("WARNING", log)
        rows = lb.aggregate([self.core])
        self.assertEqual({r["provenance"] for r in rows}, {prov.STAMPED})
        self.assertEqual({(r["model_id"], r["prompt_version"], r["window"]) for r in rows}, {("A", "v1", 20)})
        self.assertFalse(json.loads((out_dir / "provenance.json").read_text())["mixed_run_provenance"])
        rows = lb.aggregate([self.core_legacy])
        self.assertEqual({(r["model_id"], r["provenance"]) for r in rows}, {("A", prov.LEGACY)})
        self.assertEqual({r["model"] for r in rows}, {"A [sliding K=20] (core_legacy.json, catalog core_v1.jsonl)"})
        with self.assertRaises(prov.MixedRunError):        # legacy and stamped files are never pooled
            lb.aggregate([self.core, self.core_legacy])
        rows = lb.aggregate([self.core, self.core_legacy], allow_mixed=True)
        self.assertTrue(lb.PROVENANCE_REPORTS[0]["mixed"])

    def test_evaluator_and_consumers_share_the_stamp_key(self):
        self.assertEqual(prov.ROW_CONFIG_KEY, E.ROW_CONFIG_KEY)
        self.assertEqual(set(prov.COMPARE_FIELDS) | {"cf_jsonl_sha256"}, set(E.CHECKPOINT_CONFIG_FIELDS))


class TestOtherScorers(unittest.TestCase):
    """score_reasoning_pairs and score_renamed_variant on synthetic dataset roots."""

    def setUp(self):
        self.tmp_obj = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp_obj.name)
        (self.root / "counterfactuals").mkdir()
        for name in ("core_v1.jsonl", "core_v1_renamed.jsonl"):
            (self.root / "counterfactuals" / name).symlink_to(ROOT / "counterfactuals" / name)

    def tearDown(self):
        self.tmp_obj.cleanup()

    def _write(self, rel, catalog, model, prompt_version, strategy="sliding", cf=CORE_PATH, thinking="off",
               window=20):
        stamp = {**_config(cf, model, prompt_version), "strategy": strategy, "thinking": thinking, "window": window}
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({"model": model, "strategy": strategy, "window": window, "thinking": thinking,
                                    "prompt_version": prompt_version, "suffix_budget": BUDGET,
                                    "run_config": stamp, "mixed_run_configurations": False,
                                    "per_item": _oracle_rows(catalog, stamp)}))

    def _run(self, script, *extra):
        return subprocess.run([sys.executable, str(ROOT / "scripts" / script), "--dataset-root", str(self.root),
                               "--json", str(self.root / "out.json"), *extra], capture_output=True, text=True)

    def test_reasoning_pairs(self):
        for proto, strategy in (("tf1step_sliding_k20", "sliding"), ("no_suffix_feedback", "prefix_only")):
            self._write(f"reference_results/raw/deepseek_v4_flash_{proto}.json", CORE, "deepseek/deepseek-chat",
                        "v1", strategy)
            self._write(f"reference_results/reasoning_raw/deepseek_v4_flash_thinking_{proto}.json", CORE,
                        "deepseek/deepseek-reasoner", "v1.1" if proto == "no_suffix_feedback" else "v1", strategy,
                        thinking="on")
        r = self._run("score_reasoning_pairs.py")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("prompt_version", r.stderr)
        r = self._run("score_reasoning_pairs.py", "--allow-mixed")
        self.assertEqual(r.returncode, 0, r.stderr)
        d = json.loads((self.root / "out.json").read_text())["protocols"]
        self.assertTrue(d["no_suffix_feedback"]["provenance"]["mixed"])
        self.assertFalse(d["tf1step_sliding_k20"]["provenance"]["mixed"])
        self.assertEqual(d["tf1step_sliding_k20"]["on"]["model"], "deepseek/deepseek-reasoner")
        self.assertIn("WARNING: MIXED RUN PROVENANCE", d["no_suffix_feedback"]["warning"])

    def test_renamed_variant(self):
        source_edits = [r for r in CORE if r.get("patched_source")]
        renamed = sp.load_jsonl(ROOT / "counterfactuals" / "core_v1_renamed.jsonl")
        ren_path = ROOT / "counterfactuals" / "core_v1_renamed.jsonl"
        for arm, cat, cf in (("original_run1", source_edits, CORE_PATH), ("original_run2", source_edits, CORE_PATH),
                             ("renamed_run1", renamed, ren_path), ("renamed_run2", renamed, ren_path)):
            pv = "v1.1" if arm == "renamed_run2" else "v1"
            self._write(f"reference_results/renamed_raw/m_{arm}_tf1step_sliding_k20.json", cat, "A", pv, cf=cf)
        r = self._run("score_renamed_variant.py")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("prompt_version", r.stderr)
        self._write("reference_results/renamed_raw/m_renamed_run2_tf1step_sliding_k20.json", renamed, "A", "v1",
                    cf=ren_path)
        r = self._run("score_renamed_variant.py")
        self.assertEqual(r.returncode, 0, r.stderr)
        d = json.loads((self.root / "out.json").read_text())
        self.assertFalse(d["provenance"]["mixed"])
        self.assertEqual(d["model"], "A")
        self.assertEqual(d["agreement"]["original_repeat"]["value"], 100.0)


